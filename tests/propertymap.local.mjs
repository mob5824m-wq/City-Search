assert.ok(root.querySelector(".locmap__scale text"), "scale bar missing");
assert.ok(!/api key/i.test(html), "no key messaging anywhere on the page");
assert.ok(root.querySelector(".locmap__tiles img"), "street tiles expected");
assert.ok(root.querySelector(".locmap__attribution").textContent.includes("Esri"), "attribution required");
